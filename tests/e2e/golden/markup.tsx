export function renderCase(item: MarkupCase): string {
  const mentionable = new Map(Object.entries(item.users ?? users));
  const context = { serverUrl: "https://chat.example", emotes: item.emotes ?? emotes, mentionable, selfId: "u-alice" };
  return renderToStaticMarkup(<>{renderMarkup(item.text, context, <time />)}</>);
}

export function golden() {
  return {
    note: "Generated by tests/e2e/golden/markup.tsx from the desktop's lib/markup.tsx. Regenerate with UPDATE_GOLDEN=1 npm run test -w @zuna/e2e -- test/golden.test.ts",
    emotes,
    users,
    selfId: "u-alice",
    cases: corpus.map((item) => ({ text: item.text, html: renderCase(item) })),
    jumbo: jumboCorpus.map((text) => ({ text, size: jumboSize(text, emotes) })),
  };
}
