// The golden corpus for code highlighting: the desktop's highlightCode (lib/highlight.ts)
// on samples in several languages and aliases. The iOS app's Highlighter, which
// runs the same Shiki setup in JavaScriptCore, must give the same tokens
// (apps/ios/ZunaKit/Tests/ZunaHostTests/HighlighterTests.swift).

import { highlightCode } from "@/lib/highlight";

const samples: [language: string, code: string][] = [
  ["typescript", "const greet = async (name: string): Promise<void> => {\n  console.log(`hi ${name}`); // say hi\n};"],
  ["ts", "type A = { readonly id: string } & Partial<B>;"],
  ["python", "def fib(n: int) -> int:\n    return n if n < 2 else fib(n - 1) + fib(n - 2)\n"],
  ["rust", "fn main() {\n    let v: Vec<u8> = (0..10).map(|x| x * 2).collect();\n    println!(\"{:?}\", v);\n}"],
  ["swift", "struct Point: Hashable {\n    var x = 0.0, y = 0.0\n    func moved(by d: Double) -> Point { .init(x: x + d, y: y) }\n}"],
  ["json", '{ "name": "zuna", "version": 1, "tags": ["chat", true, null] }'],
  ["sh", 'for f in *.log; do echo "$f" | grep -E "^err" && rm -f "$f"; done'],
  ["go", "package main\n\nimport \"fmt\"\n\nfunc main() { fmt.Println(\"hi\") }"],
  ["sql", "SELECT id, name FROM users WHERE banned = 0 ORDER BY name LIMIT 10;"],
  ["yml", "services:\n  zuna:\n    image: ghcr.io/zuna-chat/zuna-server:latest\n    ports: [\"8787:8787\"]"],
  ["diff", "--- a/x\n+++ b/x\n@@ -1 +1 @@\n-old\n+new"],
  ["html", "<p class=\"x\">Hello <b>there</b></p>"],
];

export async function golden() {
  return {
    note: "Generated by tests/e2e/golden/highlight.ts from the desktop's lib/highlight.ts. Regenerate with UPDATE_GOLDEN=1 npm run test -w @zuna/e2e -- test/golden.test.ts",
    samples: await Promise.all(
      samples.map(async ([language, code]) => ({
        language,
        code,
        tokens: ((await highlightCode(code, language)) ?? []).map((line) => line.map((token) => [token.content, token.color ?? null])),
      })),
    ),
  };
}
